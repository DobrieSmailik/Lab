#include <iostream>
#include <string>
using namespace std;

// 1. Создайте класс оружия со следующими полями: название оружия, наносимый урон и его вес.
class Weapon {
public:
    string name;
    int damage;
    double weight;

    // 2. Создайте конструктор, принимающий 3 параметра и использующий их для инициализации переменных класса.
    Weapon(string n, int dmg, double w) {
        name = n;
        damage = dmg;
        weight = w;
    }

    // 3. Создайте конструктор без параметров, который будет вызывать конструктор из предыдущего пункта,
    // передавая туда какие-то значения по умолчанию.
    Weapon() : Weapon("Неизвестное оружие", 10, 1.5) {}
};

int main() {
    setlocale(LC_ALL, "ru");
    // 4. Создайте 2 объекта, используя конструктор с параметрами и без.
    Weapon weapon1("Меч", 25, 2.0);      // с параметрами
    Weapon weapon2;                      // без параметров (по умолчанию)

    // 5. Выведите значения всех переменных обоих экземпляров в консоль.
    cout << "Оружие 1:" << endl;
    cout << "Название: " << weapon1.name << endl;
    cout << "Урон: " << weapon1.damage << endl;
    cout << "Вес: " << weapon1.weight << " кг" << endl << endl;

    cout << "Оружие 2:" << endl;
    cout << "Название: " << weapon2.name << endl;
    cout << "Урон: " << weapon2.damage << endl;
    cout << "Вес: " << weapon2.weight << " кг" << endl;

    return 0;
}
