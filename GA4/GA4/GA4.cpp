#include <iostream>
#include <fstream>
#include <unordered_set>
#include <vector>
#include <algorithm>

int main() {
    std::ifstream in("input.txt");
    std::ofstream out("output.txt");

    std::unordered_set<long long> numbers;
    long long x;

    while (in >> x) {
        if (x > 0) {
            numbers.insert(x);
        }
        else if (x < 0) {
            numbers.erase(-x);
        }
        else { // x == 0
            break;
        }
    }

    // Копируем в вектор и сортируем
    std::vector<long long> result(numbers.begin(), numbers.end());
    std::sort(result.begin(), result.end());

    // Выводим в файл
    for (size_t i = 0; i < result.size(); ++i) {
        if (i > 0) out << " ";
        out << result[i];
    }
    // Если множество пусто — output.txt будет пустым (как и должно быть)

    return 0;
}// Запуск программы: CTRL+F5 или меню "Отладка" > "Запуск без отладки"
