#include <iostream>

// 5. Макрос для вычисления суммы двух чисел
#define SUM(a, b) ((a) + (b))

// 7. Объявляем пространство имён
namespace MyMath {

    // 1. Функция с одним параметром и статической переменной
    void processNumber(int value) {
        static int staticVar = 0; // начальное значение — 0

        // 4. Используем using внутри функции (или можно в начале файла)
        using std::cout;
        using std::endl;

        // 2. Выводим сумму переданного числа и статической переменной
        cout << "Сумма: " << (value + staticVar) << endl;

        // Присваиваем статической переменной значение переданного числа
        staticVar = value;
    }

} // namespace MyMath

// Главная функция
int main() {
    // 4. Избавляемся от std:: с помощью using
    using std::cout;
    using std::endl;

    // 3. Вызываем функцию несколько раз с разными параметрами
    MyMath::processNumber(5);   // Сумма: 5 (0 + 5)
    MyMath::processNumber(10);  // Сумма: 15 (5 + 10)
    MyMath::processNumber(3);   // Сумма: 13 (10 + 3)

    // Пример использования макроса
    int x = 7, y = 4;
    cout << "Макрос SUM(" << x << ", " << y << ") = " << SUM(x, y) << endl;

    return 0;
}
