#include <iostream>
#include <string>
using namespace std;

class Weapon {
public:
    string name;
    int damage;
    double weight;

    // Конструктор с параметрами
    Weapon(string n, int dmg, double w) : name(n), damage(dmg), weight(w) {}

    // Конструктор по умолчанию
    Weapon() : Weapon("Неизвестное оружие", 10, 1.5) {}

    // 1. Деструктор, выводящий данные оружия и сообщение об удалении
    ~Weapon() {
        cout << "[Удаление] Оружие: " << name
            << ", Урон: " << damage
            << ", Вес: " << weight << " кг" << endl;
    }

    // 5. Метод проверки: превышает ли вес оружия максимально допустимый
    bool isTooHeavy(double maxWeight) const {
        return weight > maxWeight;
    }

    // 7. Перегрузка: принимает просто вес и возвращает сумму
    double getTotalWeight(double otherWeight) const {
        return weight + otherWeight;
    }

    // 6. Метод, принимающий другой объект Weapon и возвращающий суммарный вес
    // 8. Реализован через вызов перегруженной версии (пункт 7)
    double getTotalWeight(const Weapon& other) const {
        return getTotalWeight(other.weight);
    }
};

int main() {
    setlocale(LC_ALL, "ru");
    // 2. Создаём обычный (статический) объект и выводим его данные
    cout << "=== Статический объект ===" << endl;
    Weapon sword("Меч", 30, 2.5);
    cout << "Название: " << sword.name
        << ", Урон: " << sword.damage
        << ", Вес: " << sword.weight << " кг" << endl;

    // Проверка метода isTooHeavy
    cout << "Слишком тяжёлый для 2.0 кг? " << (sword.isTooHeavy(2.0) ? "Да" : "Нет") << endl;
    cout << "Слишком тяжёлый для 3.0 кг? " << (sword.isTooHeavy(3.0) ? "Да" : "Нет") << endl;

    // 3. Создаём динамический объект
    cout << "\n=== Динамический объект ===" << endl;
    Weapon* axe = new Weapon("Топор", 40, 3.2);
    cout << "Название: " << axe->name
        << ", Урон: " << axe->damage
        << ", Вес: " << axe->weight << " кг" << endl;

    // Проверка методов getTotalWeight
    Weapon dagger("Кинжал", 15, 0.8);
    cout << "\nСуммарный вес меча и кинжала: " << sword.getTotalWeight(dagger) << " кг" << endl;
    cout << "Суммарный вес меча и 1.5 кг: " << sword.getTotalWeight(1.5) << " кг" << endl;

    // 4. Удаляем динамический объект — вызовется деструктор
    delete axe;

    // Деструктор для sword вызовется автоматически при выходе из main()
    cout << "\n[main завершён — деструктор sword будет вызван автоматически]\n" << endl;

    return 0;
}
