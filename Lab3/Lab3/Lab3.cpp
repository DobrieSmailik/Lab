#include <iostream>
using namespace std;

int main() {
    setlocale(LC_CTYPE, "Russian");
    // 1. Создайте переменную со значением на Ваше усмотрение.
    int value = 42;

    // 2. Объявите указатель на созданную переменную.
    int* ptr = &value;

    // 3. Выведите в консоль адрес указателя и значение, которое хранится по этому адресу.
    cout << "Адрес, на который указывает ptr: " << ptr << endl;
    cout << "Значение по адресу (через указатель): " << *ptr << endl;
    cout << "Значение исходной переменной: " << value << endl;
    cout << endl;

    // 4. Измените значение, которое хранится по адресу указателя.
    *ptr = 100;

    // 5. Убедитесь, что переменная из 1-го пункта так же изменила своё значение.
    cout << "После изменения через указатель:" << endl;
    cout << "Значение переменной value: " << value << endl; // должно быть 100
    cout << endl;

    // 6. Создайте массив из нескольких элементов (тип и значение на Ваше усмотрение).
    int arr[] = { 10, 20, 30, 40, 50 };
    const int size = sizeof(arr) / sizeof(arr[0]);

    // 7. Выведите все элементы массива в консоль, используя указатель.
    cout << "Элементы массива через указатель:" << endl;
    int* arrPtr = arr; // или &arr[0]
    for (int i = 0; i < size; ++i) {
        cout << *(arrPtr + i) << " ";
    }
    cout << endl << endl;

    // 8. Объявите целую переменную со значением 5.
    int number = 5;

    // 9. Создайте такой указатель на эту переменную, чтобы нельзя было менять адрес,
    // на который он ссылается, но при этом, чтобы через него можно было менять значение.
    int* const constPtr = &number; // константный указатель на int

    // 10. Убедитесь, что Вы всё сделали правильно:

    // Попытка изменить адрес — вызовет ОШИБКУ КОМПИЛЯЦИИ (закомментировано, чтобы программа компилировалась):
    // int another = 99;
    // constPtr = &another; // ❌ Ошибка: нельзя изменить адрес const-указателя

    // Но можно изменить значение по адресу:
    *constPtr = 25;

    cout << "После изменения значения через const-указатель:" << endl;
    cout << "Значение переменной number: " << number << endl; // должно быть 25

    return 0;
}
